import { execSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const wasmPkgDir = path.resolve(__dirname, '..');
const repoRoot = path.resolve(wasmPkgDir, '../..');

function findCargo() {
  try {
    execSync('cargo --version', { stdio: 'pipe' });
    return 'cargo';
  } catch {
    const isWin = process.platform === 'win32';
    const candidate = path.join(os.homedir(), '.cargo', 'bin', isWin ? 'cargo.exe' : 'cargo');
    if (fs.existsSync(candidate)) {
      return candidate;
    }
    throw new Error('Cargo not found. Please install Rust toolchain (rustup) or add ~/.cargo/bin to PATH.');
  }
}

const cargo = findCargo();
const manifestPath = path.join(wasmPkgDir, 'rust', 'Cargo.toml');
const target = 'wasm32-unknown-unknown';

console.log(`Building Rust WASM kernel using ${cargo} (target: ${target}, simd128)...`);

execSync(`"${cargo}" build --manifest-path "${manifestPath}" --target ${target} --release`, {
  cwd: repoRoot,
  stdio: 'inherit',
  env: {
    ...process.env,
    RUSTFLAGS: '-C target-feature=+simd128',
  },
});

const wasmFile = path.join(wasmPkgDir, 'rust', 'target', target, 'release', 'weaver_art_kernel.wasm');
if (!fs.existsSync(wasmFile)) {
  throw new Error(`WASM output binary not found at ${wasmFile}`);
}

const wasmBytes = fs.readFileSync(wasmFile);
const base64 = wasmBytes.toString('base64');
const outDir = path.join(wasmPkgDir, 'src', 'generated');
fs.mkdirSync(outDir, { recursive: true });
const outTs = path.join(outDir, 'kernel.ts');

const content = `// Generated by packages/wasm/scripts/build-wasm.mjs. Do not edit directly.
export const KERNEL_WASM_BASE64 = '${base64}';
`;

fs.writeFileSync(outTs, content, 'utf8');

console.log(`Generated ${outTs} (${(wasmBytes.length / 1024).toFixed(2)} KB WASM, base64 length: ${base64.length})`);
